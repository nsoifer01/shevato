// Internal link integrity for the static site.
//
// Parses the root HTML pages plus each app's index.html for href/src
// attributes and asserts that every SAME-ORIGIN reference resolves to a file
// that exists on disk AND is tracked by git. The tracked check matters
// because gitignored build output (rising-shows data/show pages, gym-tracker
// exercise pages) exists in a working clone but not in a fresh one - a link
// that only a gitignored file satisfies is a broken link on production until
// the build regenerates it, and a broken link in a clean clone always.
//
// Netlify Pretty URLs convention honored when resolving:
//   - "/apps/<slug>/"  -> apps/<slug>/index.html
//   - "/home" (no ext) -> home.html (or home/index.html)
// Skipped outright: external URLs (any scheme), protocol-relative //,
// mailto:, tel:, data:, javascript:, pure-fragment and pure-query refs.
//
// Zero dependencies; `git ls-files` is spawned once for the tracked set (CI
// always has git; if git is unavailable the tracked check degrades to
// exists-on-disk with a console note, never a false failure).

import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync, existsSync, statSync } from 'node:fs';
import { join, dirname, resolve, relative, extname, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';

const REPO_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../..');

// -- Pages under test --------------------------------------------------------

const ROOT_PAGES = [
  'index.html',
  'home.html',
  'work.html',
  'apps.html',
  'about.html',
  'contact.html',
  'privacy.html',
  'moadon-alef.html',
  '404.html'
];

// Canonical app list - pinned to apps/ directories by
// sync-system/tests/app-naming-consistency.test.mjs.
const manifest = JSON.parse(readFileSync(join(REPO_ROOT, 'assets', 'apps-manifest.json'), 'utf8'));
const APP_PAGES = manifest.apps.map((a) => join('apps', a.slug, 'index.html'));

const PARTIALS = [join('partials', 'header.html'), join('partials', 'footer.html')];

const ALL_PAGES = [...ROOT_PAGES, ...APP_PAGES, ...PARTIALS];

// -- Allowlist for legitimately runtime-generated link targets ---------------
//
// Each entry is a repo-relative path (as resolved from the href) that is
// ALLOWED to be satisfied by a gitignored or absent file, with the reason.
// Keep this list justified: anything added here is a link that 404s on a
// fresh clone until a build step runs.
const RUNTIME_GENERATED_ALLOWLIST = new Map([
  // Rising Shows SEO hub: apps/rising-shows/shows/ is generated on every
  // Netlify deploy by `npm run build:site` (build-static-pages from the
  // fetched data.json) and intentionally gitignored - see .gitignore and
  // netlify.toml [build]. Live on production; absent in a clean clone
  // until the build runs.
  ['apps/rising-shows/shows/index.html',
    'generated at deploy time by npm run build:site (rising-shows static pages)'],
  // Gym Tracker SEO hub: apps/gym-tracker/exercises/ is generated by the
  // same build (build-exercise-pages.cjs from exercises-db.json), same
  // rationale.
  ['apps/gym-tracker/exercises/index.html',
    'generated at deploy time by npm run build:site (gym-tracker exercise pages)']
]);

// -- Tracked-file set ---------------------------------------------------------

let trackedSet = null;
try {
  const out = execFileSync('git', ['ls-files', '-z'], { cwd: REPO_ROOT, maxBuffer: 64 * 1024 * 1024 });
  trackedSet = new Set(out.toString('utf8').split('\0').filter(Boolean));
} catch {
  console.warn('internal-links: git unavailable, tracked-by-git check degraded to exists-on-disk');
}

function isTracked(repoRelPath) {
  if (!trackedSet) return true; // degraded mode
  return trackedSet.has(repoRelPath.split(sep).join('/'));
}

// -- Extraction ---------------------------------------------------------------

function extractRefs(html) {
  const refs = [];
  // 1. <script src=...> before script bodies are stripped.
  for (const m of html.matchAll(/<script\b[^>]*\ssrc\s*=\s*["']([^"']+)["']/gi)) {
    refs.push(m[1]);
  }
  // 2. Strip comments, script bodies and style bodies so href/src strings
  //    inside inline JS template literals or CSS cannot false-positive.
  const stripped = html
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/<script\b[^>]*>[\s\S]*?<\/script>/gi, '')
    .replace(/<style\b[^>]*>[\s\S]*?<\/style>/gi, '');
  for (const m of stripped.matchAll(/\s(?:href|src)\s*=\s*["']([^"']+)["']/gi)) {
    refs.push(m[1]);
  }
  return refs;
}

function isExternal(ref) {
  return /^[a-z][a-z0-9+.-]*:/i.test(ref) || ref.startsWith('//');
}

/**
 * Resolve a same-origin ref to candidate files on disk, honoring the
 * Pretty-URLs convention. Returns null when the ref needs no file check.
 */
function candidatesFor(pageRelPath, ref) {
  const pathPart = ref.split('#')[0].split('?')[0];
  if (pathPart === '') return null; // pure fragment or query
  let decoded;
  try { decoded = decodeURIComponent(pathPart); } catch { decoded = pathPart; }

  const abs = decoded.startsWith('/')
    ? resolve(REPO_ROOT, decoded.slice(1) || '.')
    : resolve(REPO_ROOT, dirname(pageRelPath), decoded);

  if (decoded.endsWith('/')) return [join(abs, 'index.html')];
  if (extname(abs) !== '') return [abs];
  // Extensionless: Netlify maps /home -> home.html; a directory link written
  // without the trailing slash also resolves.
  return [`${abs}.html`, join(abs, 'index.html')];
}

function checkPage(pageRelPath) {
  const html = readFileSync(join(REPO_ROOT, pageRelPath), 'utf8');
  const problems = [];

  for (const ref of new Set(extractRefs(html))) {
    if (isExternal(ref)) continue;
    const candidates = candidatesFor(pageRelPath, ref);
    if (!candidates) continue;

    // Allowlisted build-generated targets may be untracked OR entirely
    // absent (fresh clone, CI) - both are fine, the deploy build creates them.
    const candRels = candidates.map((c) => relative(REPO_ROOT, c).split(sep).join('/'));
    if (candRels.some((r) => RUNTIME_GENERATED_ALLOWLIST.has(r))) continue;

    const existing = candidates.find((c) => existsSync(c) && statSync(c).isFile());
    if (!existing) {
      problems.push(`broken link "${ref}" (no file at ${candidates.map((c) => relative(REPO_ROOT, c)).join(' or ')})`);
      continue;
    }

    const repoRel = relative(REPO_ROOT, existing);
    if (!isTracked(repoRel)) {
      problems.push(
        `link "${ref}" is satisfied only by gitignored/untracked file ${repoRel} - ` +
        'it would 404 on a clean clone; either commit the target or allowlist it with a reason'
      );
    }
  }
  return problems;
}

// -- Tests ---------------------------------------------------------------------

for (const page of ALL_PAGES) {
  test(`internal links resolve in ${page}`, () => {
    assert.ok(existsSync(join(REPO_ROOT, page)), `page ${page} is missing`);
    assert.deepEqual(checkPage(page), [], `broken same-origin references in ${page}`);
  });
}

test('the allowlist only contains entries that are actually untracked', () => {
  // An allowlist entry for a file that IS tracked is stale documentation.
  const stale = [...RUNTIME_GENERATED_ALLOWLIST.keys()].filter((p) => isTracked(p));
  assert.deepEqual(stale, [], 'remove tracked files from RUNTIME_GENERATED_ALLOWLIST');
});
